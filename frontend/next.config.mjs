const isDev = process.env.NODE_ENV !== "production";

// Only NEXT_PUBLIC_* values may reach the browser; everything else is server-only.
const ALLOWED_PUBLIC_ENV = new Set(["NEXT_PUBLIC_SITE_URL", "NEXT_PUBLIC_ANALYTICS_ID"]);
for (const key of Object.keys(process.env)) {
  if (key.startsWith("NEXT_PUBLIC_") && !ALLOWED_PUBLIC_ENV.has(key)) {
    throw new Error(`Refusing to build: unexpected public env var ${key} (add it to ALLOWED_PUBLIC_ENV if safe).`);
  }
}

const csp = [
  "default-src 'self'",
  `script-src 'self' 'unsafe-inline'${isDev ? " 'unsafe-eval'" : ""}`,
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "font-src 'self'",
  `connect-src 'self'${isDev ? " ws:" : ""}`,
  "frame-ancestors 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "object-src 'none'",
  ...(isDev ? [] : ["upgrade-insecure-requests"]),
].join("; ");

/** @type {import('next').NextConfig} */
const nextConfig = {
  reactStrictMode: true,
  poweredByHeader: false,
  images: {
    formats: ["image/avif", "image/webp"],
  },
  async headers() {
    return [
      {
        source: "/:path*",
        headers: [
          { key: "Content-Security-Policy", value: csp },
          { key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains; preload" },
          { key: "X-Content-Type-Options", value: "nosniff" },
          { key: "X-Frame-Options", value: "DENY" },
          { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
          { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=(), interest-cohort=()" },
        ],
      },
    ];
  },
};

export default nextConfig;
